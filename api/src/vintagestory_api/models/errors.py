"""Machine-readable error codes for API responses."""


class ErrorCode:
    """Centralized error codes used across the API.

    These codes are returned in error responses for machine parsing.
    Human-readable messages accompany them for debugging.
    """

    # Authentication
    UNAUTHORIZED = "UNAUTHORIZED"
    FORBIDDEN = "FORBIDDEN"

    # Server lifecycle
    SERVER_NOT_RUNNING = "SERVER_NOT_RUNNING"
    SERVER_NOT_INSTALLED = "SERVER_NOT_INSTALLED"
    SERVER_ALREADY_RUNNING = "SERVER_ALREADY_RUNNING"
    SERVER_RUNNING = "SERVER_RUNNING"
    SERVER_START_FAILED = "SERVER_START_FAILED"
    SERVER_STOP_FAILED = "SERVER_STOP_FAILED"
    SERVER_ALREADY_STOPPED = "SERVER_ALREADY_STOPPED"

    # Mods
    MOD_NOT_FOUND = "MOD_NOT_FOUND"
    MOD_NOT_INSTALLED = "MOD_NOT_INSTALLED"
    MOD_INCOMPATIBLE = "MOD_INCOMPATIBLE"
    MOD_ALREADY_INSTALLED = "MOD_ALREADY_INSTALLED"
    MOD_STATE_CORRUPT = "MOD_STATE_CORRUPT"
    MOD_FILE_CORRUPT = "MOD_FILE_CORRUPT"
    INVALID_SLUG = "INVALID_SLUG"

    # Config
    INVALID_CONFIG = "INVALID_CONFIG"
    CONFIG_NOT_FOUND = "CONFIG_NOT_FOUND"
    CONFIG_FILE_NOT_FOUND = "CONFIG_FILE_NOT_FOUND"
    CONFIG_PATH_INVALID = "CONFIG_PATH_INVALID"
    # Story 19.1 (Epic 19 ADR-1): the config file viewer serves regular .json files
    # that are UTF-8 text, up to 2 MiB
    CONFIG_FILE_NOT_SUPPORTED = "CONFIG_FILE_NOT_SUPPORTED"
    CONFIG_FILE_TOO_LARGE = "CONFIG_FILE_TOO_LARGE"
    # Story 23.4 (Epic 23 ADR-4): saving a config file's text
    CONFIG_FILE_INVALID = "CONFIG_FILE_INVALID"
    CONFIG_FILE_SERVER_RUNNING = "CONFIG_FILE_SERVER_RUNNING"
    CONFIG_FILE_SERVER_BUSY = "CONFIG_FILE_SERVER_BUSY"
    CONFIG_FILE_CHANGED = "CONFIG_FILE_CHANGED"
    CONFIG_FILE_WRITE_FAILED = "CONFIG_FILE_WRITE_FAILED"
    # Story 23.6 (Epic 23 ADR-7): config file history
    CONFIG_HISTORY_WRITE_FAILED = "CONFIG_HISTORY_WRITE_FAILED"
    CONFIG_REVISION_INVALID = "CONFIG_REVISION_INVALID"
    CONFIG_REVISION_NOT_FOUND = "CONFIG_REVISION_NOT_FOUND"

    # Game Settings (Epic 6) - serverconfig.json settings managed via console commands
    # These apply to VintageStory game server configuration (Port, ServerName, etc.)
    SETTING_UNKNOWN = "SETTING_UNKNOWN"
    SETTING_ENV_MANAGED = "SETTING_ENV_MANAGED"
    SETTING_UPDATE_FAILED = "SETTING_UPDATE_FAILED"
    SETTING_VALUE_INVALID = "SETTING_VALUE_INVALID"
    # Story 25.3: a setting the game keeps changes only while it runs and is ready
    SETTING_NEEDS_RUNNING_SERVER = "SETTING_NEEDS_RUNNING_SERVER"

    # API Settings (Story 6.3) - api-settings.json for management API configuration
    # These apply to API operational settings (auto_start, refresh intervals, etc.)
    API_SETTING_UNKNOWN = "API_SETTING_UNKNOWN"
    API_SETTING_INVALID = "API_SETTING_INVALID"
    # Story 17.6: saved, but its job could not be rescheduled (applies at restart)
    API_SETTING_NOT_APPLIED = "API_SETTING_NOT_APPLIED"

    # External APIs
    EXTERNAL_API_ERROR = "EXTERNAL_API_ERROR"
    EXTERNAL_API_TIMEOUT = "EXTERNAL_API_TIMEOUT"
    DOWNLOAD_FAILED = "DOWNLOAD_FAILED"
    GAME_VERSION_NOT_FOUND = "GAME_VERSION_NOT_FOUND"

    # Mod Installation
    MOD_VERSION_NOT_FOUND = "MOD_VERSION_NOT_FOUND"
    MOD_UPDATE_CHECK_IN_PROGRESS = "MOD_UPDATE_CHECK_IN_PROGRESS"
    MOD_UPDATE_ALL_IN_PROGRESS = "MOD_UPDATE_ALL_IN_PROGRESS"
    MOD_CONFIRMATION_REQUIRED = "MOD_CONFIRMATION_REQUIRED"
    MOD_OPERATION_IN_PROGRESS = "MOD_OPERATION_IN_PROGRESS"
    MOD_VALIDATION_FAILED = "MOD_VALIDATION_FAILED"
    MOD_RELEASE_NOT_DOWNLOADABLE = "MOD_RELEASE_NOT_DOWNLOADABLE"
    MOD_VERSION_CHANGE_FAILED = "MOD_VERSION_CHANGE_FAILED"
    MOD_FILE_CONFLICT = "MOD_FILE_CONFLICT"
    MOD_FILE_MISSING = "MOD_FILE_MISSING"
    # Story 24.5 (Epic 24 ADR-3, ADR-4): rescan and unused files
    MODS_BUSY = "MODS_BUSY"
    UNUSED_FILE_NOT_FOUND = "UNUSED_FILE_NOT_FOUND"
    UNUSED_FILE_DELETE_FAILED = "UNUSED_FILE_DELETE_FAILED"

    # Server installation
    INVALID_VERSION = "INVALID_VERSION"
    VERSION_NOT_SUPPORTED = "VERSION_NOT_SUPPORTED"
    VERSION_NOT_FOUND = "VERSION_NOT_FOUND"
    SERVER_ALREADY_INSTALLED = "SERVER_ALREADY_INSTALLED"
    INSTALLATION_FAILED = "INSTALLATION_FAILED"
    INSTALLATION_IN_PROGRESS = "INSTALLATION_IN_PROGRESS"
    CHECKSUM_MISMATCH = "CHECKSUM_MISMATCH"
    UNINSTALL_FAILED = "UNINSTALL_FAILED"

    # Jobs (Epic 7)
    JOB_NOT_FOUND = "JOB_NOT_FOUND"

    # General
    VALIDATION_ERROR = "VALIDATION_ERROR"
    INTERNAL_ERROR = "INTERNAL_ERROR"
